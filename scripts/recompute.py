"""Recompute the published summaries with Python's standard library only."""

import csv
from itertools import combinations
from math import sqrt
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
JUDGES = ('deepseek', 'gemini', 'grok', 'kimi', 'opus', 'sol')
ENTRIES = tuple('ABCDEFGHIJKLM')
ROUND2 = tuple('ABCGIJM')
AXES = ('skill_fit', 'emotive', 'creativity')
OWN = dict(deepseek=('F', 'G'), gemini=('B', 'K'), grok=('A', 'E'),
           kimi=('C', 'D'), opus=('H', 'I'), sol=('J', 'L'))


def read_csv(name):
    with (ROOT / name).open(newline='', encoding='utf-8') as stream:
        return list(csv.DictReader(stream))


def pearson(xs, ys):
    if len(xs) != len(ys) or len(xs) < 2:
        raise ValueError('Paired samples of length >= 2 required')
    xbar, ybar = mean(xs), mean(ys)
    numerator = sum((x - xbar) * (y - ybar) for x, y in zip(xs, ys))
    denominator = sqrt(sum((x - xbar) ** 2 for x in xs) *
                       sum((y - ybar) ** 2 for y in ys))
    if not denominator:
        raise ValueError('Correlation requires nonconstant inputs')
    return numerator / denominator


def ranks(values):
    """Ascending ranks with average ranks for tied scores."""
    order = sorted(range(len(values)), key=values.__getitem__)
    result = [0.0] * len(values)
    start = 0
    while start < len(order):
        end = start + 1
        while end < len(order) and values[order[end]] == values[order[start]]:
            end += 1
        average_rank = (start + 1 + end) / 2
        for index in order[start:end]:
            result[index] = average_rank
        start = end
    return result


def spearman(xs, ys):
    return pearson(ranks(xs), ranks(ys))


def table(headers, rows):
    print('| ' + ' | '.join(headers) + ' |')
    print('| ' + ' | '.join('---' for _ in headers) + ' |')
    for row in rows:
        print('| ' + ' | '.join(map(str, row)) + ' |')
    print()


def main():
    raw_meta = read_csv('entries.csv')
    meta = {row['entry']: row for row in raw_meta}
    assert len(raw_meta) == 13 and set(meta) == set(ENTRIES)
    raw_one = read_csv('round1-scores.csv')
    one = {row['entry']: {key: float(row[key]) for key in ('john',) + JUDGES}
           for row in raw_one}
    assert len(raw_one) == 13 and set(one) == set(ENTRIES)
    raw_two = read_csv('round2-scores.csv')
    two = {(row['judge'], row['entry']): {axis: float(row[axis]) for axis in AXES}
           for row in raw_two}
    assert len(raw_two) == 42 and set(two) == {(j, e) for j in JUDGES for e in ROUND2}
    assert all(1 <= value <= 10 for row in one.values() for value in row.values())
    assert all(1 <= value <= 10 for row in two.values() for value in row.values())
    words = {e: int(meta[e]['original_word_count']) for e in ENTRIES}
    assert all(value > 0 for value in words.values())

    panel = {e: mean(one[e][j] for j in JUDGES) for e in ENTRIES}
    two_panel = {e: {a: mean(two[j, e][a] for j in JUDGES) for a in AXES} for e in ROUND2}
    print('# Recomputed results\n')
    print('Generated by `scripts/recompute.py` from the published CSVs. '
          'Scores use the entry labels printed in the original ballots; known '
          'ballot errors are discussed in [RESULTS_AUDIT.md](RESULTS_AUDIT.md).\n')
    print('## Round 1\n')
    table(['Panel rank', 'Entry', 'Writer', 'Format', 'John', 'Panel mean'],
          [(i, e, meta[e]['writer'], meta[e]['format'], f"{one[e]['john']:g}", f'{panel[e]:.2f}')
           for i, e in enumerate(sorted(ENTRIES, key=lambda e: (-panel[e], e)), 1)])
    for subset, label in [(ENTRIES, 'all 13 entries'), (tuple(e for e in ENTRIES if e != 'M'), '12 model entries, excluding M')]:
        rho = spearman([one[e]['john'] for e in subset], [panel[e] for e in subset])
        print(f'- John versus panel mean, Spearman rho ({label}): **{rho:.4f}**.')
    pairs = [spearman([one[e][a] for e in ENTRIES], [one[e][b] for e in ENTRIES])
             for a, b in combinations(JUDGES, 2)]
    print(f'- Pairwise judge Spearman rho: mean **{mean(pairs):.4f}**, '
          f'range **{min(pairs):.4f} to {max(pairs):.4f}** across 15 pairs.\n')
    print('Format means average entries equally; the two-format comparison excludes human entry M.\n')
    table(['Format', 'Model entries', 'John mean', 'Panel mean'],
          [(form, len(es), f"{mean(one[e]['john'] for e in es):.4f}", f'{mean(panel[e] for e in es):.4f}')
           for form in ('15-beat', 'story-engine')
           for es in [[e for e in ENTRIES if e != 'M' and meta[e]['format'] == form]]])
    es = [e for e in ENTRIES if meta[e]['format'] == '15-beat']
    print(f'Including M: 15-beat John mean = {mean(one[e]["john"] for e in es):.4f}; '
          f'panel mean = {mean(panel[e] for e in es):.4f} (n=7).\n')
    table(['Writer', 'John mean', 'Panel mean'],
          [(writer, f'{mean(one[e]["john"] for e in es):.4f}', f'{mean(panel[e] for e in es):.4f}')
           for writer in sorted({meta[e]['writer'] for e in ENTRIES if e != 'M'})
           for es in [[e for e in ENTRIES if meta[e]['writer'] == writer]]])

    print('## Round 2\n')
    table(['Entry', 'Original words', 'Skill fit', 'Emotive', 'Creativity'],
          [(e, words[e], *(f'{two_panel[e][a]:.2f}' for a in AXES)) for e in ROUND2])
    print('Pearson r between original whole-file word count and mean score. '
          'The Grok-excluded rows are a sensitivity analysis for mismatched commentary, '
          'not a correction or relabeling of that ballot.\n')
    correlations = []
    for judges, judge_label in [(JUDGES, 'All six judges'), (tuple(j for j in JUDGES if j != 'grok'), 'Excluding Grok')]:
        for entries, entry_label in [(ROUND2, 'All seven entries'), (tuple(e for e in ROUND2 if e != 'M'), 'Six model entries')]:
            correlations.append((judge_label, entry_label, *(f'{pearson([words[e] for e in entries], [mean(two[j,e][a] for j in judges) for e in entries]):.4f}' for a in AXES)))
    table(['Judges', 'Entries', 'Skill fit r', 'Emotive r', 'Creativity r'], correlations)

    print('## Descriptive self-preference checks\n')
    print("A judge's score on its own model family's entry minus the mean of the other "
          'five judges on that same entry. Positive values favor its own family. '
          'Round 1 averages two entries; round 2 uses the one 15-beat entry. '
          'These small descriptive differences do not establish presence or absence of bias.\n')
    table(['Judge', 'Round 1 mean delta', 'Round 2 skill-fit delta'],
          [(j, f'{mean(one[e][j] - mean(one[e][other] for other in JUDGES if other != j) for e in OWN[j]):+.4f}',
            f'{mean(two[j,e]["skill_fit"] - mean(two[other,e]["skill_fit"] for other in JUDGES if other != j) for e in OWN[j] if e in ROUND2):+.4f}')
           for j in JUDGES])
    print('## Counting and interpretation\n')
    print('Original word counts are whitespace-delimited counts of the complete blinded files '
          'before publication metadata cleanup (equivalent to `wc -w`); headings and '
          'assessments are included. They are stored in `entries.csv` so metadata edits '
          'do not silently change historical correlations. Correlations and ranks use '
          'unrounded scores. Spearman uses average ranks for score ties, not the judges\' '
          'separate prose tie-breaks.\n')
    print('These are descriptive associations from one story and a small, related set '
          'of entries. They do not establish a causal length effect, population-wide '
          'model rankings, or a statistically tested absence of self-preference.')


if __name__ == '__main__':
    main()
